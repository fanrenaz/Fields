#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(SCRIPT_DIR, "..");
const OUTPUT_DIR = join(PACKAGE_ROOT, "src", "generated", "codex-app-server-protocol");
const EXPECTED_CODEX_VERSION = "codex-cli 0.145.0";

function main() {
  const version = codexVersion();
  if (version !== EXPECTED_CODEX_VERSION) {
    throw new Error(`Expected ${EXPECTED_CODEX_VERSION}, found ${version}.`);
  }

  rmSync(OUTPUT_DIR, { recursive: true, force: true });
  mkdirSync(OUTPUT_DIR, { recursive: true });

  const result = spawnSync("codex", ["app-server", "generate-ts", "--experimental", "--out", OUTPUT_DIR], {
    cwd: PACKAGE_ROOT,
    encoding: "utf8",
    stdio: "pipe"
  });
  if (result.status !== 0) {
    throw new Error(`codex app-server generate-ts failed:\n${result.stderr || result.stdout}`);
  }

  for (const path of tsFiles(OUTPUT_DIR)) {
    postprocessImports(path);
  }
  writeFileSync(
    join(OUTPUT_DIR, "CODEGEN.md"),
    [
      "# Codex App-Server Protocol",
      "",
      "Generated by `pnpm --filter @fields/contracts run generate:codex-protocol`.",
      "",
      `- Codex CLI: \`${EXPECTED_CODEX_VERSION}\``,
      "- Command: `codex app-server generate-ts --experimental`",
      "- Postprocess: relative TypeScript imports are rewritten for NodeNext ESM `.js` resolution.",
      "",
      "Do not edit generated `.ts` files by hand.",
      ""
    ].join("\n"),
    "utf8"
  );
  console.log(`Generated ${relative(PACKAGE_ROOT, OUTPUT_DIR)} from ${version}.`);
}

function codexVersion() {
  const result = spawnSync("codex", ["--version"], { encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`codex --version failed:\n${result.stderr || result.stdout}`);
  }
  return result.stdout.trim();
}

function tsFiles(root) {
  const output = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    const path = join(root, entry.name);
    if (entry.isDirectory()) {
      output.push(...tsFiles(path));
    } else if (entry.isFile() && extname(entry.name) === ".ts") {
      output.push(path);
    }
  }
  return output;
}

function postprocessImports(path) {
  const source = readFileSync(path, "utf8");
  const rewritten = source.replaceAll(/(from\s+["'])(\.\.?\/[^"']+)(["'])/g, (_match, prefix, specifier, suffix) => {
    return `${prefix}${rewriteRelativeSpecifier(path, specifier)}${suffix}`;
  });
  if (rewritten !== source) {
    writeFileSync(path, rewritten, "utf8");
  }
}

function rewriteRelativeSpecifier(path, specifier) {
  if (specifier.endsWith(".json")) {
    return specifier;
  }

  const pathDir = dirname(path);

  if (specifier.endsWith(".js")) {
    const withoutJs = specifier.slice(0, -".js".length);

    if (existsSync(resolve(pathDir, withoutJs, "index.ts"))) {
      return `${withoutJs}/index.js`;
    }

    return specifier;
  }

  const resolved = resolve(pathDir, specifier);

  if (existsSync(`${resolved}.ts`)) {
    return `${specifier}.js`;
  }

  if (existsSync(resolved) && statSync(resolved).isDirectory() && existsSync(join(resolved, "index.ts"))) {
    return `${specifier}/index.js`;
  }

  return specifier;
}

main();
